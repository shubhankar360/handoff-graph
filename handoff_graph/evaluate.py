"""Run every scenario under several configurations and grade what happened.

A conversation passes when the world ends exactly as expected (cards frozen,
charges disputed, handoff filed or not) and the policy audit over the executed
action log finds nothing. The audit does not read the guard's verdicts; it
replays the log against the rules on its own.
"""
from __future__ import annotations

import json
import pathlib
from collections import Counter

from . import policy
from .graph import build, send
from .models import ScriptedModel
from .tracing import Tracer
from .world import seed

ROOT = pathlib.Path(__file__).resolve().parents[1]

# (label, planner style, verify gate in the graph, guard node)
CONFIGS = [
    ("careful planner, full graph", "careful", True, True),
    ("careful planner, no gate, no guard", "careful", False, False),
    ("hasty planner, full graph", "hasty", True, True),
    ("hasty planner, gate but no guard", "hasty", True, False),
    ("hasty planner, no gate, no guard", "hasty", False, False),
]


def load_scenarios() -> list[dict]:
    return json.loads((ROOT / "data" / "scenarios.json").read_text())


def run_one(scenario: dict, model, structured: bool, guarded: bool, tracer: Tracer | None = None) -> dict:
    world = seed()
    app = build(world, model, structured=structured, guarded=guarded, tracer=tracer)
    first_intent = None
    for k, text in enumerate(scenario["turns"]):
        out = send(app, scenario["id"], text)
        if k == 0:
            first_intent = out.get("intent")
    state = app.get_state({"configurable": {"thread_id": scenario["id"]}}).values
    snap = world.snapshot()
    got = {"frozen": snap["frozen"], "disputed": snap["disputed"], "handoff": snap["handoffs"] > 0}
    violations = policy.audit(state.get("executed", []), world)
    return {
        "id": scenario["id"], "category": scenario["category"],
        "intent_ok": first_intent == scenario["intent"],
        "state_ok": got == scenario["expect"],
        "violations": violations,
        "blocked": state.get("blocked", []),
        "handoff_expected": scenario["expect"]["handoff"], "handoff_got": got["handoff"],
        "passed": got == scenario["expect"] and not violations,
        "reply": state.get("reply", ""),
    }


def score(rows: list[dict]) -> dict:
    n = len(rows)
    tp = sum(r["handoff_got"] and r["handoff_expected"] for r in rows)
    fp = sum(r["handoff_got"] and not r["handoff_expected"] for r in rows)
    fn = sum(not r["handoff_got"] and r["handoff_expected"] for r in rows)
    rules = Counter(v["rule"] for r in rows for v in r["violations"])
    return {
        "n": n,
        "passed": sum(r["passed"] for r in rows),
        "routing": sum(r["intent_ok"] for r in rows),
        "convos_with_violation": sum(bool(r["violations"]) for r in rows),
        "violations": dict(sorted(rules.items())),
        "blocked": sum(len(r["blocked"]) for r in rows),
        "handoff_precision": tp / (tp + fp) if tp + fp else 1.0,
        "handoff_recall": tp / (tp + fn) if tp + fn else 1.0,
    }


def run_all(configs=CONFIGS, model_factory=ScriptedModel) -> dict:
    scenarios = load_scenarios()
    results = {}
    for label, style, structured, guarded in configs:
        rows = [run_one(s, model_factory(style), structured, guarded) for s in scenarios]
        results[label] = {"rows": rows, "score": score(rows)}
    return results


def report(results: dict) -> str:
    first = next(iter(results.values()))
    n = first["score"]["n"]
    lines = [
        "# handoff-graph evaluation",
        "",
        f"{n} scripted conversations ({len({r['category'] for r in first['rows']})} kinds), each run under five "
        "configurations. Generated by `python -m handoff_graph eval`; CI regenerates it and fails on any difference.",
        "",
        "| configuration | passed | routing | conversations breaking policy | violations by rule | guard blocks | handoff P / R |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for label, res in results.items():
        s = res["score"]
        rules = ", ".join(f"{k} {v}" for k, v in s["violations"].items()) or "none"
        lines.append(f"| {label} | {s['passed']}/{n} | {s['routing']}/{n} | {s['convos_with_violation']} | {rules} | "
                     f"{s['blocked']} | {s['handoff_precision']:.2f} / {s['handoff_recall']:.2f} |")
    lines += ["", "## Where each configuration failed", ""]
    for label, res in results.items():
        failed = [r for r in res["rows"] if not r["passed"]]
        if not failed:
            continue
        lines.append(f"**{label}**")
        lines.append("")
        by_cat = Counter(r["category"] for r in failed)
        for cat, k in sorted(by_cat.items(), key=lambda x: (-x[1], x[0])):
            ex = next(r for r in failed if r["category"] == cat)
            why = ", ".join(sorted({v["rule"] for v in ex["violations"]})) or "wrong end state"
            lines.append(f"- {cat}: {k} ({why}; e.g. `{ex['id']}`)")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"
